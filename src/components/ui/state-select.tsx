const StateSelect = ({ selected, onChange }: StateSelectProps) => {
  const [open, setOpen] = React.useState(false);

  const selectedState = states.find(state => state.value === selected);

  return (
    <Popover open={open} onOpenChange={setOpen}>
      <PopoverTrigger asChild>
        <Button
          variant="outline"
          role="combobox"
          aria-expanded={open}
          className="w-full justify-between"
        >
          {selectedState ? selectedState.label : "Select state..."}
          <ChevronsUpDown className="ml-2 h-4 w-4 shrink-0 opacity-50" />
        </Button>
      </PopoverTrigger>
      <PopoverContent className="w-full p-0" align="start">
        <Command>
          <CommandInput placeholder="Search states..." />
          <CommandList className="max-h-[300px]">
            <CommandEmpty>No state found.</CommandEmpty>
            <CommandGroup>
              <CommandItem
                onSelect={() => {
                  onChange(undefined);
                  setOpen(false);
                }}
              >
                <Check
                  className={cn(
                    "mr-2 h-4 w-4",
                    !selected ? "opacity-100" : "opacity-0"
                  )}
                />
                All states
              </CommandItem>
              {states.map((state) => (
                <CommandItem
                  key={state.value}
                  onSelect={() => {
                    onChange(selected === state.value ? undefined : state.value);
                    setOpen(false);
                  }}
                >
                  <Check
                    className={cn(
                      "mr-2 h-4 w-4",
                      selected === state.value ? "opacity-100" : "opacity-0"
                    )}
                  />
                  {state.label}
                </CommandItem>
              ))}
            </CommandGroup>
          </CommandList>
        </Command>
      </PopoverContent>
    </Popover>
  );
};

